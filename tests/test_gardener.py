class Lines(unittest.TestCase):
    def test_every_file_lands_in_one_bucket(self):
        cases = {
            "shop/cart.py": "production", "shop/cart_test.go": "tests", "tests/test_cart.py": "tests",
            "web/cart.test.tsx": "tests", "web/__tests__/cart.js": "tests", "spec/cart_spec.rb": "tests",
            "mocks/store.go": "generated", "package-lock.json": "generated", "README.md": "docs",
            "docs/plan.html": "docs", ".github/workflows/ci.yml": "config", "Dockerfile": "config",
        }
        for path, bucket in cases.items():
            self.assertEqual(lines.bucket_of(path, ""), bucket, path)

    def test_a_generated_header_wins_over_the_path(self):
        self.assertEqual(lines.bucket_of("api/types.go", "// Code generated by x. DO NOT EDIT.\n"), "generated")

    def test_added_lines_keep_their_number_and_kind(self):
        stats = lines.collect(DIFF)
        cart, test = stats["files"]
        self.assertEqual([(no, kind) for no, kind, _ in cart["lines"]],
                         [(2, "doc"), (3, "code"), (4, "code"), (5, "blank"), (45, "code")])
        self.assertEqual((test["bucket"], test["code"], test["doc"]), ("tests", 1, 1))


class Scores(unittest.TestCase):
    def setUp(self):
        self.stats = lines.collect(DIFF)

    def test_scope_is_the_share_of_lines_beyond_what_is_needed(self):
        review = {"pieces": [
            {"name": "Add up a cart", "role": "core", "needs": 2, "ranges": [{"file": "shop/cart.py", "start": 2, "end": 4}]},
            {"name": "Spare", "role": "beyond", "ranges": [{"file": "shop/cart.py", "start": 45, "end": 45}]},
            {"name": "Its test", "role": "unsure", "ranges": [{"file": "shop/cart.test.ts", "start": 1, "end": 2}]},
        ]}
        m = scope.model(self.stats, review)
        # The first piece needs both of its code lines, so its comment line is needed too.
        self.assertEqual((m["has"], m["need"], m["unsure"], m["extra"]), (6, 3, 2, 1))
        self.assertAlmostEqual(m["share"], 100 * 1 / 6)
        self.assertEqual([r["name"] for r in m["over"]], ["Spare", "Its test"])
        self.assertEqual(m["unplaced"], 0)

    def test_a_kept_piece_keeps_its_tests_and_a_share_of_its_comments(self):
        ranges = [{"file": "shop/cart.py", "start": 2, "end": 45}, {"file": "shop/cart.test.ts", "start": 1, "end": 2}]
        row = scope.model(self.stats, {"pieces": [{"role": "core", "needs": 2, "ranges": ranges}]})["rows"][0]
        self.assertEqual((row["has"], row["needs"]), (6, 5))   # 2 of 3 code lines, 1 comment line, both test lines

    def test_a_line_claimed_twice_counts_once(self):
        piece = {"role": "beyond", "ranges": [{"file": "shop/cart.py", "start": 2, "end": 4}]}
        m = scope.model(self.stats, {"pieces": [piece, piece]})
        self.assertEqual([r["has"] for r in m["rows"]], [3, 0])

    def test_weight_counts_only_added_lines_of_the_right_kind(self):
        findings = [
            {"category": "doc_restates_code", "file": "shop/cart.py", "start": 1, "end": 60},   # one comment line in range
            {"category": "code_needless_check", "file": "shop/cart.py", "start": 45, "end": 45},
            {"category": "code_duplicate", "file": "shop/cart.test.ts", "start": 1, "end": 2},  # a code finding in a test file
            {"category": "no_such_category", "file": "shop/cart.py", "start": 3, "end": 3},
        ]
        m = weight.model(self.stats, findings)
        self.assertEqual((m["flagged"], m["base"]), (2, 6))
        self.assertEqual((len(m["kept"]), len(m["dropped"])), (2, 2))

    def test_the_marks_split_ok_borderline_and_above(self):
        self.assertEqual([card.outcome(v, (20, 30)) for v in (19.9, 20, 30, 30.1)], ["pass", "warn", "warn", "fail"])


class Post(unittest.TestCase):
    def setUp(self):
        self.stats = lines.collect(DIFF)
        self.wm = weight.model(self.stats, [{"category": "code_needless_check", "file": "shop/cart.py", "start": 3, "end": 45, "reason": "r"}])

    def test_a_finding_across_two_hunks_gets_one_comment_with_a_full_range_link(self):
        comments = github.weight_comments(self.wm, DIFF, "o/r", "abc")
        self.assertEqual([(c.get("start_line"), c["line"]) for c in comments], [(3, 4)])
        self.assertIn("https://github.com/o/r/blob/abc/shop/cart.py#L3-L45", comments[0]["body"])

    def test_small_reviews_go_inline_and_larger_reviews_fold_every_finding(self):
        diff = "diff --git a/shop/cart.py b/shop/cart.py\n+++ b/shop/cart.py\n@@ -0,0 +1,6 @@\n" + "+check()\n" * 6
        stats = lines.collect(diff)
        findings = [
            {"category": "code_needless_check", "file": "shop/cart.py", "start": line, "end": line,
             "reason": f"Check at {line}", "see": "shop/cart.py:1"}
            for line in range(1, 7)
        ]
        sm = scope.model(stats, {"purpose": "p", "pieces": []})
        cfg = {"scope_limits": (20, 30), "weight_limits": (10, 15)}

        for count, inline_count in ((0, 0), (5, 5), (6, 0)):
            with self.subTest(count=count), mock.patch.object(github, "upload", return_value="assets"), mock.patch.object(github, "gh") as gh:
                gh.side_effect = [[], {"html_url": "https://github.com/o/r/pull/1"}]
                wm = weight.model(stats, findings[:count])
                github.publish("o/r", 1, "abc", sm, wm, stats, diff, cfg)
                post = gh.call_args.args[2]
                self.assertEqual(len(post["comments"]), inline_count)
                if count == 6:
                    self.assertIn("<summary>6 weight findings</summary>", post["body"])
                    for line in range(1, 7):
                        self.assertIn(f"https://github.com/o/r/blob/abc/shop/cart.py#L{line}", post["body"])
                else:
                    self.assertNotIn("<summary>", post["body"])

    def test_a_later_push_posts_only_findings_without_live_threads(self):
        sm = scope.model(self.stats, {"purpose": "p", "pieces": []})
        cfg = {"scope_limits": (20, 30), "weight_limits": (10, 15)}
        prior = {"id": 7, "body": "<!-- gardener scope=40.00 weight=10.00 -->"}
        old_thread = github.weight_comments(self.wm, DIFF, "o/r", "old")[0]
        wm = weight.model(self.stats, self.wm["kept"] + [
            {"category": "test_unneeded", "file": "shop/cart.test.ts", "start": 2, "end": 2, "reason": "Repeated test"},
        ])
        with mock.patch.object(github, "upload", return_value="assets"), mock.patch.object(github, "gh") as gh:
            gh.side_effect = [[prior], [old_thread], None, None]
            github.publish("o/r", 1, "abc", sm, wm, self.stats, DIFF, cfg)
        _, _, post, update = gh.call_args_list
        self.assertEqual(post.args[0], "POST")
        self.assertEqual([comment["path"] for comment in post.args[2]["comments"]], ["shop/cart.test.ts"])
        self.assertNotIn("<summary>", update.args[2]["body"])

    def test_a_rejected_inline_review_still_leaves_the_findings_in_the_main_review(self):
        sm = scope.model(self.stats, {"purpose": "p", "pieces": []})
        cfg = {"scope_limits": (20, 30), "weight_limits": (10, 15)}
        prior = {"id": 7, "body": "<!-- gardener scope=40.00 weight= -->"}
        with mock.patch.object(github, "upload", return_value="assets"), mock.patch.object(github, "gh") as gh:
            gh.side_effect = [[prior], [], RuntimeError("could not validate comment position"), None]
            result = github.publish("o/r", 1, "abc", sm, self.wm, self.stats, DIFF, cfg)
        self.assertIn("could not validate comment position", result)
        update = gh.call_args_list[-1]
        self.assertEqual(update.args[:2], ("PUT", "repos/o/r/pulls/1/reviews/7"))
        self.assertIn("https://github.com/o/r/blob/abc/shop/cart.py#L3-L45", update.args[2]["body"])

    def test_the_card_is_valid_svg_with_and_without_weight(self):
        sm = scope.model(self.stats, {"purpose": "Add up a cart & more <fast>", "pieces": []})
        for wm in (None, self.wm):
            for theme in ("light", "dark"):
                xml.dom.minidom.parseString(card.render(sm, wm, theme, start={"scope": 55.0, "weight": 20.0}))

    def test_later_posts_keep_the_scores_of_the_first(self):
        sm = scope.model(self.stats, {"purpose": "p", "pieces": []})
        cfg = {"scope_limits": (20, 30), "weight_limits": (10, 15)}
        text = github.body(sm, self.wm, "o/r", "abc", "l", "d", cfg, start={"scope": 61.5, "weight": None})
        _, start = github.first_review([{"body": "unrelated"}, {"body": text}])
        self.assertEqual(start, {"scope": 61.5, "weight": round(self.wm["share"], 2)})


